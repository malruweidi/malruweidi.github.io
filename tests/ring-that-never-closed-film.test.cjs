"use strict";
const test=require("node:test"),assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path"),crypto=require("node:crypto");
const root=path.resolve(__dirname,".."),read=p=>fs.readFileSync(path.join(root,p),"utf8");
const m=JSON.parse(read("assets/films/ring-that-never-closed-scenes.json"));
test("chemistry screenplay documents the failed route and never manufactures a success",()=>{
 assert.equal(m.running_seconds,180);assert.equal(m.scenes.length,10);
 let t=0;for(const s of m.scenes){assert.equal(s.start,t);assert.ok(s.narration.length>45);t+=s.duration;}assert.equal(t,180);
 assert.equal(m.grant_id,"UREP23-133-1-028");assert.equal(m.chemical_observations.isolated_schiff_bases,3);
 assert.equal(m.chemical_observations.absorbance_band_decrease_nm_approx,380);
 assert.equal(m.chemical_observations.absorbance_band_increase_nm_approx,450);
 assert.equal(m.chemical_observations.detection_limit_molar,1.42e-5);
 assert.match(m.scientific_integrity,/not proof of selectivity/);
 assert.match(m.scientific_integrity,/PRMT5/);
 assert.ok(fs.existsSync(path.join(root,m.source_figure)));
 const original=read("stories/the-ring-that-never-closed.html");
 assert.match(original,/ring closure/);
 assert.match(original,/1.42/);
});
test("separate 180-second final MP4 has true container signature, caption timeline and reproducibility checksum",()=>{
 const video=fs.readFileSync(path.join(root,"assets/films/ring-that-never-closed.mp4"));
 assert.ok(video.length>1_000_000);
 assert.equal(video.subarray(4,8).toString(),"ftyp");
 const build=JSON.parse(read("assets/films/ring-that-never-closed-build.json"));
 assert.equal(build.video_sha256,crypto.createHash("sha256").update(video).digest("hex"));
 assert.ok(Math.abs(build.seconds-180)<.20);
 assert.equal(build.scene_count,10);
 assert.match(read("assets/films/ring-that-never-closed.vtt"),/^WEBVTT/);
 assert.ok((read("assets/films/ring-that-never-closed.vtt").match(/-->/g)||[]).length>=20);
});
test("the released film has source links, transcript, original story and discoverability without losing previously published films",()=>{
 const page=read("films/the-ring-that-never-closed.html");
 const hub=read("films.html"),story=read("stories/the-ring-that-never-closed.html");
 assert.ok(page.includes("/assets/films/ring-that-never-closed.mp4"));
 assert.ok(page.includes("/assets/films/ring-that-never-closed.vtt"));
 assert.ok(page.includes('href="/stories/the-ring-that-never-closed.html"'));
 assert.ok(page.includes('href="/grants/urep23.html"'));
 for(const s of m.scenes)assert.ok(page.includes(s.narration),"Missing full narration for "+s.id);
 assert.ok(page.includes("1.42 × 10"));
 assert.match(page,/not a simulated UV/);
 assert.ok(hub.includes('href="/films/the-ring-that-never-closed.html"'));
 assert.ok(hub.includes("what-survives-the-experiment.mp4"));
 assert.ok(hub.includes("cairo-microscope.mp4"));
 assert.ok(hub.includes("airway-reopening-evidence-cut.mp4"));
 assert.ok(story.includes("The final report describes three such compounds"));
 const j=JSON.parse(read("assets/discovery-index.json"));
 assert.ok(j.items.some(x=>x.url==="/films/the-ring-that-never-closed.html"));
 assert.ok(read("sitemap.xml").includes("https://malruweidi.github.io/films/the-ring-that-never-closed.html"));
});
